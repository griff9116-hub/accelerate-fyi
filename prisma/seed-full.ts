async function main() {
  console.log("Seeding full programme database...");
  console.log(`Total programmes to upsert: ${programmes.length}\n`);

  let created = 0;
  let skipped = 0;

  for (const programme of programmes) {
    const result = await prisma.programme.upsert({
      where: { slug: programme.slug },
      update: {}, // skip update if already exists — safe to re-run
      create: {
        ...programme,
        isActive: true,
        applicationDeadline: null,
        nextCohortDate: null,
      },
    });

    // Check if the record was just created or already existed
    const wasJustCreated =
      result.createdAt.getTime() > Date.now() - 5000;
    if (wasJustCreated) {
      console.log(`  ✓ Created: ${programme.name} (${programme.country})`);
      created++;
    } else {
      console.log(`  → Skipped: ${programme.name} (already exists)`);
      skipped++;
    }
  }

  console.log(`\nDone!`);
  console.log(`  Created: ${created}`);
  console.log(`  Skipped: ${skipped}`);
  console.log(`  Total:   ${programmes.length}`);
}

